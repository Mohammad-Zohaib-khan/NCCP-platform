-- MFA enrolment support (additive): pending secret during enrolment, last accepted TOTP step for replay protection.
ALTER TABLE users ADD COLUMN IF NOT EXISTS mfa_pending_secret_enc text;
ALTER TABLE users ADD COLUMN IF NOT EXISTS mfa_last_step bigint;
ALTER TABLE users ADD COLUMN IF NOT EXISTS mfa_enrolled_at timestamptz;

-- Short-lived challenge issued after a correct password when MFA is required (second login step).
CREATE TABLE IF NOT EXISTS mfa_challenges (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id     uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash  text NOT NULL UNIQUE,
  attempts    integer NOT NULL DEFAULT 0,
  ip_address  inet,
  created_at  timestamptz NOT NULL DEFAULT now(),
  expires_at  timestamptz NOT NULL,
  used_at     timestamptz
);
CREATE INDEX IF NOT EXISTS mfa_challenges_user_idx ON mfa_challenges (user_id) WHERE used_at IS NULL;
